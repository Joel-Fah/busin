// Writes the wordmark's path data from the portal (apps/admin_web/components/brand/paths.ts) into the Flutter design
// system, so the logo can be drawn and filled in the apps from one source:
//   node tools/export-brand-paths.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(path.join(root, "apps/admin_web/components/brand/paths.ts"), "utf8");

const viewBox = source.match(/BRAND_VIEWBOX = "([^"]+)"/)?.[1];
if (!viewBox) throw new Error("No BRAND_VIEWBOX in paths.ts");
const [, , width, height] = viewBox.split(" ").map(Number);

const paths = [...source.matchAll(/\{ d: "([^"]+)", evenodd: (true|false) \}/g)].map((m) => ({ d: m[1], evenOdd: m[2] === "true" }));
if (paths.length === 0) throw new Error("No paths found in paths.ts");

const out = `// GENERATED by tools/export-brand-paths.mjs from apps/admin_web/components/brand/paths.ts. Do not edit by hand.

/// The BusIn wordmark as SVG path data, so it can be drawn as an outline and then filled.
const double brandWidth = ${width};
const double brandHeight = ${height};

/// One entry per shape: the SVG path data and whether it is filled with the even-odd rule (letters cut out of a sticker).
const List<({String d, bool evenOdd})> brandPaths = [
${paths.map((p) => `  (d: '${p.d}', evenOdd: ${p.evenOdd}),`).join("\n")}
];
`;
writeFileSync(path.join(root, "packages/busin_ui/lib/src/brand/brand_paths.dart"), out);
console.log(`${paths.length} paths, ${width} x ${height}`);
