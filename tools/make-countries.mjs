// Writes the list of countries for the phone fields (ADR 0024), the same on the web and in the Flutter apps: the
// two-letter code, the dialling code and the name in English and French. Codes and dialling codes come from the
// libphonenumber metadata, names from the platform's Intl (CLDR). Run after updating libphonenumber-js:
//   node tools/make-countries.mjs
// It also copies their flags (country-flag-icons, MIT) to apps/admin_web/public/flags and packages/busin_ui/assets/flags.
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'apps/admin_web/package.json'));
const { getCountries, getCountryCallingCode } = require('libphonenumber-js/max');

const en = new Intl.DisplayNames(['en'], { type: 'region' });
const fr = new Intl.DisplayNames(['fr'], { type: 'region' });
const countries = getCountries()
  .map((code) => ({ code, dial: getCountryCallingCode(code), en: en.of(code) ?? code, fr: fr.of(code) ?? code }))
  .sort((a, b) => a.en.localeCompare(b.en, 'en'));

const header = 'Generated by tools/make-countries.mjs from the libphonenumber metadata and CLDR names. Do not edit by hand.';
const ts = `// ${header}\n\nexport type Country = { code: string; dial: string; en: string; fr: string };\n\nexport const COUNTRIES: readonly Country[] = [\n${countries
  .map((c) => `  { code: ${JSON.stringify(c.code)}, dial: ${JSON.stringify(c.dial)}, en: ${JSON.stringify(c.en)}, fr: ${JSON.stringify(c.fr)} },`)
  .join('\n')}\n];\n`;
writeFileSync(path.join(root, 'apps/admin_web/lib/phone/countries.ts'), ts);

const dartString = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const dart = `// ${header}\n\n/// A country for the phone field: two-letter code, dialling code, and its name in English and French.\nclass PhoneCountry {\n  const PhoneCountry(this.code, this.dial, this.en, this.fr);\n\n  final String code;\n  final String dial;\n  final String en;\n  final String fr;\n\n  /// The name in [language] (\`en\` or \`fr\`).\n  String name(String language) => language == 'fr' ? fr : en;\n}\n\nconst phoneCountries = <PhoneCountry>[\n${countries
  .map((c) => `  PhoneCountry(${dartString(c.code)}, ${dartString(c.dial)}, ${dartString(c.en)}, ${dartString(c.fr)}),`)
  .join('\n')}\n];\n`;
writeFileSync(path.join(root, 'packages/busin_ui/lib/src/phone/countries.dart'), dart);
// The flags, as small SVG files served from the portal (emoji flags are not allowed here): only those in the list.
const flags = path.join(path.dirname(require.resolve('country-flag-icons/package.json')), '3x2');
// The same files on the web (public/flags) and in the Flutter apps (busin_ui assets), so both show the same flags.
const outs = [path.join(root, 'apps/admin_web/public/flags'), path.join(root, 'packages/busin_ui/assets/flags')];
for (const out of outs) mkdirSync(out, { recursive: true });
let copied = 0;
for (const { code } of countries) {
  const file = path.join(flags, `${code}.svg`);
  if (existsSync(file)) {
    for (const out of outs) copyFileSync(file, path.join(out, `${code}.svg`));
    copied++;
  }
}
console.log(`${countries.length} countries written, ${copied} flags copied.`);
